/**
 * 根据选择的方法论ID列表，组装完整的 system prompt
 */
export function buildNeedSensingPrompt(
  selectedMethodIds: string[],
  customMethodPrompts?: Record<string, string>,
  methodModes?: Record<string, string>,
  problemType: ProblemType = 'product',
  language?: string,
): string {
  // 筛选选中的方法论
  const selectedMethods = INNOVATION_METHODS.filter(m => selectedMethodIds.includes(m.id));

  // 如果没有选择任何方法论，使用全部
  const methods = selectedMethods.length > 0 ? selectedMethods : INNOVATION_METHODS;

  // 组装每个方法论的 Prompt（支持自定义覆盖，支持多模式选择）
  const methodPrompts = methods.map(method => {
    // 优先使用自定义 prompt，其次使用 mode 专属 prompt，最后使用默认 prompt
    const customPrompt = customMethodPrompts?.[method.id];
    const selectedModeId = methodModes?.[method.id];
    let prompt: string;
    if (customPrompt) {
      prompt = customPrompt;
    } else if (selectedModeId && method.modes) {
      const mode = method.modes.find(m => m.id === selectedModeId);
      prompt = mode?.prompt || method.prompt;
    } else {
      prompt = method.prompt;
    }
    const nameSuffix = selectedModeId && method.modes
      ? ` - ${method.modes.find(m => m.id === selectedModeId)?.name || ''}`
      : '';
    return `### 方法论：${method.fullName}（${method.name}${nameSuffix}）\n\n${prompt}`;
  }).join('\n\n---\n\n');

  return `${problemContext(problemType)}\n${EVIDENCE_RULES}\n${NEED_SENSING_FRAMEWORK_PROMPT}\n\n---\n\n**你需要运用以下创新方法论（选择适用步骤，说明依据与局限）**：\n\n${methodPrompts}\n\n---\n\n**额外的结构化输出要求**：\n在分析报告的末尾，用以下JSON格式输出创新方向摘要（放在\`\`\`json代码块中）：\n\`\`\`json\n{\n  "directions": [\n    {\n      "title": "方向标题",\n      "description": "方向的完整描述内容（包含该方向的核心逻辑、目标用户、关键假设等）"\n    }\n  ]\n}\n\`\`\`\n每个方向必须包含title和description字段；description保留证据属性、约束、未知项与最小验证动作。若资料不足无法提出方向，directions返回空数组并列出澄清问题。\n${EVIDENCE_RULES}\n${outputLanguage(language)}`;
}

/**
 * 获取单个方法论的默认 Prompt（用于编辑器初始化）
 */
export function getMethodDefaultPrompt(methodId: string, modeId?: string): string {
  const method = INNOVATION_METHODS.find(m => m.id === methodId);
  if (!method) return '';
  if (modeId && method.modes) {
    const mode = method.modes.find(m => m.id === modeId);
    return mode?.prompt || method.prompt;
  }
  return method.prompt;
}
